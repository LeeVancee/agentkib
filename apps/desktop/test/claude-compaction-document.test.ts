describe("rowTurn", () => {
  const call = {
    line: 1,
    value: {
      ...assistant("c1", null, "x"),
      message: {
        role: "assistant",
        content: [{ type: "tool_use", id: "call-1", name: "grep", input: { query: "needle" } }],
      },
    },
  };
  const result = {
    line: 2,
    value: {
      ...user("r1", "c1", "x"),
      message: {
        role: "user",
        content: [{ type: "tool_result", tool_use_id: "call-1", content: "found" }],
      },
    },
  };

  it("uses the caller's known calls to decide whether a tool result is orphaned", () => {
    const known = new Set<string>();
    const losses = new Map();
    expect(rowTurn(call, known, losses)?.blocks[0]).toMatchObject({
      type: "tool-call",
      call_id: "call-1",
    });
    expect(rowTurn(result, known, losses)?.blocks[0]).toMatchObject({
      type: "tool-result",
      output: "found",
    });
    expect(losses.size).toBe(0);

    const isolated = new Map();
    expect(rowTurn(result, new Set(), isolated)).not.toBeNull();
    expect(isolated.get("orphan-tool-result")).toBe(1);
  });

  it("returns null for rows without readable content", () => {
    const losses = new Map();
    expect(rowTurn({ line: 3, value: { type: "user", uuid: "n" } }, new Set(), losses)).toBeNull();
    expect(
      rowTurn(
        { line: 4, value: { ...user("n2", null, ""), message: { role: "user", content: [] } } },
        new Set(),
        losses,
      ),
    ).toBeNull();
  });
});

