const SUMMARY_NOTICE =
  "[AgentKib: context summary generated by Claude Code when it compacted this conversation. It summarizes earlier turns and is not a message written by the user.]";
const summaryBlock = (body: string) => `${SUMMARY_NOTICE}\n\n${body}`;
const boundaryNote = (index: number, total: number, trigger?: "auto" | "manual") =>
  `[AgentKib: Claude Code compacted the conversation here (compaction ${index} of ${total}${trigger ? `, trigger: ${trigger}` : ""}). Messages above are the original earlier history; the context summary below is what Claude carried forward.]`;
const unlinkedNote = (index: number, total: number) =>
  `[AgentKib: Claude Code compacted the conversation here (compaction ${index} of ${total}). Earlier history before this point could not be located in the transcript and is not included.]`;
const noSummaryNote = (index: number, total: number, trigger?: "auto" | "manual") =>
  `[AgentKib: Claude Code compacted the conversation here (compaction ${index} of ${total}${trigger ? `, trigger: ${trigger}` : ""}). Messages above are the original earlier history; no context summary was found in the transcript.]`;

function fileFor(records: readonly unknown[]): string {
  const root = mkdtempSync(path.join(os.tmpdir(), "claude-compaction-"));
  roots.push(root);
  const file = path.join(root, "session.jsonl");
  writeFileSync(file, jsonlLines(records));
  return file;
}
function documentFor(
  records: readonly unknown[],
  options?: DocumentOptions,
  includeSidechain = false,
): SessionDocument {
  return readClaudeDocument(source, fileFor(records), includeSidechain, options);
}
